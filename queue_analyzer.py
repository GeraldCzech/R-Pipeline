def analyze_results(script_name, stdout, stderr):
    """
    Main analyzer function called after each successful job.
    Decides what follow-up analyses to add.
    """
    logger.info(f"Analyzing results from: {script_name}")

    # Route to appropriate analyzer
    if "bsem" in script_name.lower():
        analyze_bsem_results(script_name, stdout, stderr)
    elif "robma" in script_name.lower():
        analyze_robma_results(script_name, stdout, stderr)
    elif "elasticnet" in script_name.lower():
        analyze_elasticnet_results(script_name, stdout, stderr)
    elif "dominance" in script_name.lower():
        analyze_dominance_results(script_name, stdout, stderr)

    logger.info(f"Analysis complete for: {script_name}")


