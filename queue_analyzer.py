def add_subgroup_analysis(base_script, subgroup_var):
    """Generate a subgroup analysis script."""
    # Example: if base_script is "003_bsem_faircloth.R" and subgroup_var is "gender"
    # Create "003b_bsem_faircloth_subgroup_gender.R"

    if subgroup_var not in ["gender", "organization_type"]:
        return

