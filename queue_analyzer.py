LOG_DIR = Path(PIPELINE_ROOT) / "logs"

logging.basicConfig(
    level=logging.INFO,
    format="[%(asctime)s] %(levelname)s: %(message)s",
    handlers=[
        logging.FileHandler(LOG_DIR / "queue_analyzer.log"),
    ]
)
logger = logging.getLogger(__name__)


def add_to_queue(script_name, script_content):
    """Add a new .R script to queue/pending/."""
    script_path = PENDING_DIR / script_name
    if script_path.exists():
        logger.warning(f"Script already exists, skipping: {script_name}")
        return False

    try:
        with open(script_path, "w") as f:
            f.write(script_content)
        logger.info(f"✅ Added to queue: {script_name}")
        return True
    except Exception as e:
        logger.error(f"Error adding to queue: {e}")
        return False


def parse_log_file(log_path):
    """Parse output log file and extract key metrics."""
    try:
        with open(log_path, "r") as f:
            content = f.read()
        return content
    except Exception as e:
        logger.error(f"Error reading log: {e}")
        return None


